UUID = re.compile(r"finding-[0-9a-f]{32}\Z")


def canonical(value):
    """Omit only the scanner's top-level per-run issue correlation token.

    Nested evidence is security material even if it contains a field named
    finding_id and happens to resemble a generated identifier.
    """
    if not isinstance(value, dict):
        raise ValueError("invalid security issue")
    value = dict(value)
    item = value.get("finding_id")
    if isinstance(item, str) and UUID.fullmatch(item):
        value.pop("finding_id")
    return value


def security(report):
    issues = report.get("issues")
    if not isinstance(issues, list) or any(not isinstance(x, dict) for x in issues):
        raise ValueError("invalid original security findings")
    return collections.Counter(json.dumps(canonical(x), sort_keys=True,
        ensure_ascii=False, separators=(",", ":")) for x in issues
        if not (x.get("id") in {"AE1", "AE7"} and x.get("tags") == ["coverage"]))


def key(value):
    if not isinstance(value, dict):
        raise ValueError("invalid reference")
    return json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(",", ":"))


def compare(old, new, case):
    name, revision, path, blob, line, kind, literal = case
    a, b = (v["analysis_completeness"]["references"] for v in (old, new))
    if not isinstance(a, list) or not isinstance(b, list):
        raise ValueError("unavailable reference evidence")
    deleted = collections.Counter(map(key, a)) - collections.Counter(map(key, b))
    added = collections.Counter(map(key, b)) - collections.Counter(map(key, a))
    expected = [x for x in a if x.get("source_path") == "SKILL.md"
        and x.get("line") == line and x.get("reference_kind") == kind
        and x.get("status") == "missing" and literal in x.get("evidence", "")]
    if len(expected) != 1 or added:
        raise ValueError("source-bound reference evidence differs")
    if name == "generator":
        # The genuine primary instructions are dynamically downloaded by an
        # unpinned npm CLI. An inert generator comment is not proof that the
        # remotely served instructions have been inspected; never promote it.
        if (deleted or old["analysis_completeness"]["status"] !=
            new["analysis_completeness"]["status"] or
            old["analysis_completeness"]["is_complete"] !=
            new["analysis_completeness"]["is_complete"]):
            raise ValueError("dynamic primary instructions cannot be certified")
    elif deleted != collections.Counter([key(expected[0])]):
        raise ValueError("unexpected source-bound reference difference")
    if security(old) != security(new):
        raise ValueError("content/security finding changed")
    refs = new["analysis_completeness"]["references"]
    if new["analysis_completeness"]["is_complete"] and any(
        x.get("status") == "missing" and x.get("reference_kind") == "inline_command"
        for x in refs):
        raise ValueError("uninspected executable falsely claimed Complete")
    if name.startswith("license"):
        coverage = new["analysis_completeness"]
        if (
            coverage["status"] != "complete"
            or coverage["is_complete"] is not True
            or coverage.get("partially_inspected_files", 0) != 0
            or coverage.get("entirely_uninspected_files", 0) != 0
            or any(row.get("status") != "resolved" for row in refs)
        ):
            raise ValueError("SPDX source still has unresolved inspection evidence")
    return {"name": name, "source_revision": revision, "source_blob": blob,
        "previous_status": old["analysis_completeness"]["status"],
        "candidate_status": new["analysis_completeness"]["status"],
        "previous_references": len(a), "candidate_references": len(b),
        "metadata_rows_removed": 0 if name == "generator" else 1,
        "dynamic_primary_instructions_unverified": name == "generator",
        "other_security_findings_preserved": True}



def source_risks(retained: dict, candidate: dict) -> dict:
    """Require every prior signed risk still at same source line and severity.

    V3 groups and newer raw scanner issues have different wrappers and random
    finding IDs. The upstream Git SHA and full SKILL.md blob are separately
    pinned; preserve each observed rule, severity, path and start line.
    """
    if (
        retained.get("status") != "partial"
        or retained.get("freshness") != "current"
        or retained.get("findings_truncated") is not False
        or retained.get("coverage", {}).get("grouping_complete") is not True
        or not isinstance(retained.get("findings"), list)
        or not isinstance(candidate.get("issues"), list)
    ):
        raise ValueError("invalid signed source baseline evidence")
    a = collections.Counter()
    for finding in retained["findings"]:
        if not isinstance(finding, dict) or type(finding.get("raw_count")) is not int:
            raise ValueError("invalid signed risk group")
        if finding["raw_count"] != 1:
            raise ValueError("unqualified multi-occurrence original group")
        fingerprint = finding.get("match_fingerprint")
        if not isinstance(fingerprint, str) or re.fullmatch(r"[0-9a-f]{64}", fingerprint) is None:
            raise ValueError("unqualified signed finding fingerprint")
        a[(finding["rule"], finding["severity"], finding["path"], finding["line"],
           fingerprint)] += 1
    b = collections.Counter()
    for finding in candidate["issues"]:
        if not isinstance(finding, dict):
            raise ValueError("malformed newer issue")
        if finding.get("id") in {"AE1", "AE7"} and finding.get("tags") == ["coverage"]:
            continue
        location = finding.get("location")
        if not isinstance(location, dict):
            raise ValueError("missing candidate finding location")
        fingerprint = finding.get("match_fingerprint")
        if not isinstance(fingerprint, str) or re.fullmatch(r"[0-9a-f]{64}", fingerprint) is None:
            raise ValueError("candidate missing source-bound fingerprint")
        b[(finding.get("id"), finding.get("severity"),
            location.get("file"), location.get("start_line"), fingerprint)] += 1
    missing = a - b
    if missing:
        raise ValueError("candidate lost source-bound original signed risk")
    return {"original_signed_groups": sum(a.values()),
            "candidate_content_issues": sum(b.values()),
            "no_signed_security_finding_lost": True}


# Independently check the exact producer's agentplugins-tree-sha256-v1
# digest, including nested paths, directories, file bytes and executable modes.
# The scanner-only scan_tree() hash is a separate test fingerprint and does not
# establish equivalence with the signed original acquisition.
_SOURCE_TREE_DOMAIN = b"agentplugins.package-tree\x00sha256\x00v1"


def signed_source_tree_digest(root: Path) -> str:
    if root.is_symlink() or not root.is_dir() or not (root / "SKILL.md").is_file():
        raise ValueError("invalid signed-source root")
    entries = []
    seen = set()
    size = 0
    for path in root.rglob("*"):
        relative = path.relative_to(root).as_posix()
        folded = relative.casefold()
        if (relative in {".git", ".plugin-kit-ai.lock"} or
                relative.startswith(".git/") or path.is_symlink() or
                folded in seen):
            raise ValueError("untrusted or colliding signed-source entry")
        seen.add(folded)
        if path.is_dir():
            entries.append((relative.encode(), b"directory", b"040000", b"", b""))
        elif path.is_file():
            content = path.read_bytes()
            size += len(content)
            if size > 16 << 20 or len(entries) >= 2048:
                raise ValueError("signed-source inventory exceeds bound")
            mode = b"100755" if path.stat().st_mode & 0o111 else b"100644"
            entries.append((relative.encode(), b"file", mode, b"", content))
        else:
            raise ValueError("unsupported signed-source entry")
    digest = hashlib.sha256()
    digest.update(len(_SOURCE_TREE_DOMAIN).to_bytes(8, "big"))
    digest.update(_SOURCE_TREE_DOMAIN)
    for relative, kind, mode, target, content in sorted(entries, key=lambda x: x[0]):
        for field in (b"entry", relative, kind, mode, target):
            digest.update(len(field).to_bytes(8, "big"))
            digest.update(field)
        digest.update(len(content).to_bytes(8, "big"))
        if kind == b"file":
            digest.update(content)
    return "sha256:" + digest.hexdigest()


def published_by_skill(checkout: Path) -> dict:
    if head(checkout) != PUBLISHED_REPORT_COMMIT:
        raise ValueError("immutable report checkout was not pinned")
    content = (checkout / PUBLISHED_SHARD_REL).read_bytes()
    if hashlib.sha256(content).hexdigest() != PUBLISHED_SHARD_DIGEST:
        raise ValueError("published v3 shard digest differs from signed manifest")
    shard = json.loads(content)
    if shard.get("schema_version") != 3 or shard.get("repository") != "lucas-magalhaes1/keycloak-power":
        raise ValueError("wrong immutable signed shard")
    rows = shard.get("records")
    if not isinstance(rows, list) or len(rows) != 11:
        raise ValueError("original immutable source set changed")
    selected = {}
    for row in rows:
        source = row.get("source")
        if isinstance(source, dict) and source.get("revision") == CASES[0][1]:
            if source.get("path") in selected:
                raise ValueError("ambiguous original source path")
            selected[source.get("path")] = row
    return selected

def head(root):
    return subprocess.check_output(["git", "-C", str(root), "rev-parse", "HEAD"],
        text=True).strip()


def main():
    p = argparse.ArgumentParser()
    for name in ("baseline", "candidate", "license", "generator", "published", "output"):
        p.add_argument("--" + name, type=Path, required=True)
    args = p.parse_args()
    for path, expected in ((args.baseline, BASE), (args.candidate, CANDIDATE)):
        if head(path) != expected:
            raise ValueError("scanner Git pin differs")
    published = published_by_skill(args.published)
    measured = []
    for case in CASES:
        name, revision, path, blob, line, kind, literal = case
        root = args.generator if name == "generator" else args.license
        if head(root) != revision:
            raise ValueError("source Git pin differs")
        skill = root / path
        content = (skill / "SKILL.md").read_bytes()
        git_blob = hashlib.sha1(b"blob " + str(len(content)).encode() + b"\0" + content).hexdigest()
        if git_blob != blob:
            raise ValueError("source SKILL.md blob differs")
        before = scan_tree(skill)
        old_exit, old = run(args.baseline / ".venv/bin/skillspector", skill,
                            allow_risk_exit=True)
        if scan_tree(skill) != before:
            raise ValueError("old scanner modified source")
        new_exit, new = run(args.candidate / ".venv/bin/skillspector", skill,
                            allow_risk_exit=True)
        if scan_tree(skill) != before:
            raise ValueError("candidate scanner modified source")
        # A retained security risk above score 50 causes CLI exit 1 even
        # when all source bytes were inspected. Never suppress that signal.
        old_score, new_score = public_risk_score(old), public_risk_score(new)
        if (old_score != new_score or
                old.get("risk_assessment") != new.get("risk_assessment")):
            raise ValueError("independent security risk assessment changed")
        comparison = compare(old, new, case)
        if name.startswith("license"):
            original = published.get(path)
            if original is None or original["source"]["revision"] != revision:
                raise ValueError("signed baseline source identity missing")
            actual_digest = signed_source_tree_digest(skill)
            if actual_digest != original["source"].get("content_digest"):
                raise ValueError("scanned source tree differs from original signed-source content digest")
            comparison["original_source_content_digest_verified"] = actual_digest
            comparison.update(source_risks(original, new))
        measured.append({**comparison, "source_tree_sha256": before,
            "baseline_exit": old_exit, "candidate_exit": new_exit,
            "retained_security_risk_score": new_score,
            "risk_based_cli_exit_retained": new_score > 50})
    result = {"schema_version": 1, "kind": "skillspector-2134-metadata-readonly",
        "base_scanner": BASE, "candidate_scanner": CANDIDATE,
        "safe_for_automatic_publication": False, "results": measured}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, sort_keys=True, indent=2) + "\n")
    print(json.dumps(result, sort_keys=True))


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, KeyError, subprocess.SubprocessError) as exc:
        print("Native source E2E rejected: " + str(exc), file=sys.stderr)
        sys.exit(1)
